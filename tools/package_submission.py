def allowed(path: Path) -> bool:
    return (not any(x in SKIP_DIRS for x in path.parts)
            and not (path.name.startswith(".env") and path.name != ".env.example")
            and path.name not in {".maintainer", "settings.local.json", "scheduled_tasks.lock"}
            and path.suffix not in {".pyc", ".tmp", ".lock"})


def write(name: str, value: str) -> None:
    target = OUT / name
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(value.strip() + "\n", encoding="utf-8")


def main() -> None:
    if OUT.exists():
        raise SystemExit(f"Destination already exists; refusing to overwrite: {OUT}")
    OUT.mkdir(parents=True)
    for folder in DIRS:
        for source in (ROOT / folder).rglob("*"):
            if source.is_file() and allowed(source.relative_to(ROOT)):
                destination = OUT / source.relative_to(ROOT)
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(source, destination)
    for name in FILES:
        shutil.copy2(ROOT / name, OUT / name)
